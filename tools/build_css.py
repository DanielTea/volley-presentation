#!/usr/bin/env python3
"""Write the stylesheet that the page serves: the design system's four sheets as one file, without their comments.

The copies under assets/ds/css are the design system's own files, unchanged, and nine tenths of them are comments:
1.3 MB as files, 430 KB once the server has compressed them. A phone at a trade fair waits for all of it before
it draws anything. This script joins the four sheets in the order the design system prescribes and takes out
the comments and the blank lines they leave, and nothing else. No rule, value or order changes. The result is
about 250 KB, 40 KB compressed.

    python3 tools/build_css.py           write assets/ds/css/cf.bundle.css
    python3 tools/build_css.py --check   fail if the bundle is not what the four sheets give now

Run it after refreshing the copies of the design system (see the README).
"""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SHEETS = ('tokens.css', 'base.css', 'components.css', 'landing-v2.css')
SOURCE = ROOT / 'assets' / 'ds' / 'css'
BUNDLE = SOURCE / 'cf.bundle.css'
HEAD = ('/* Control-F design system: tokens.css, base.css, components.css and the landing page\'s section styles,\n'
        '   joined in that order with their comments removed. Generated by tools/build_css.py; edit nothing here. */\n')


def strip_comments(css: str) -> str:
    """The stylesheet without its comments. A comment opener inside a string or a url() is text, not a comment."""
    out, i, n = [], 0, len(css)
    while i < n:
        ch = css[i]
        if ch in '"\'':                                   # a string: copy it whole, escapes included
            j = i + 1
            while j < n and css[j] != ch:
                j += 2 if css[j] == '\\' else 1
            out.append(css[i:j + 1])
            i = j + 1
        elif css.startswith('/*', i):
            j = css.find('*/', i + 2)
            if j < 0:
                raise ValueError('a comment is never closed')
            out.append(' ')
            i = j + 2
        elif css[i:i + 4].lower() == 'url(':             # an unquoted url: copy to its closing bracket
            j = css.find(')', i)
            body = css[i + 4:j].lstrip()
            if body[:1] in '"\'':                         # quoted after all: let the string branch take it
                out.append(css[i:i + 4])
                i += 4
            else:
                out.append(css[i:j + 1])
                i = j + 1
        else:
            out.append(ch)
            i += 1
    lines = (line.rstrip() for line in ''.join(out).splitlines())
    return '\n'.join(line for line in lines if line.strip()) + '\n'


def build() -> str:
    parts = [HEAD]
    for name in SHEETS:
        parts.append(f'/* {name} */\n' + strip_comments((SOURCE / name).read_text(encoding='utf-8')))
    return ''.join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='compare instead of writing')
    args = parser.parse_args()
    css = build()
    if args.check:
        if not BUNDLE.exists() or BUNDLE.read_text(encoding='utf-8') != css:
            print(f'{BUNDLE.relative_to(ROOT)} is stale: run python3 tools/build_css.py', file=sys.stderr)
            return 1
        print(f'{BUNDLE.relative_to(ROOT)} is current')
        return 0
    BUNDLE.write_text(css, encoding='utf-8')
    before = sum((SOURCE / name).stat().st_size for name in SHEETS)
    print(f'{BUNDLE.relative_to(ROOT)}: {len(css.encode()):,} bytes from {before:,}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
